def _strip_peek(session):
    names = session.get('names')
    if isinstance(names, list):
        session['names'] = [entry for entry in names
                            if not (entry and entry[0] == PEEK)]


def session_save(session, _self=cmd, **_kwargs):
    """Session-save task. Keeps the peek object out of every session dictionary, so it
    can never come back from a .pse as a real object. Never touches the store."""
    _strip_peek(session)
    return 1


def warn_if_pse_leaves_sets(filename='', _self=cmd):
    """Called by `save` on the .pse/.psw path (not from the session task: `get_session`
    is also used for reads like the group-membership check, and a warning on every read
    would be noise). Names the sets a plain .pse leaves behind.

    A set whose EVERY entry is staged is not named: each of its structures is an object
    in the .pse, so nothing is lost -- and since #416 every single design has a
    one-entry set behind it, a warning there would fire on every save of every session
    that ever ran a design. Only the links and the columns stay behind, which is what the
    words say.
    """
    if _SAVING_RAYMOL or not store.is_open():
        return False
    try:
        c = container()
        names = [s['name'] for s in c.sets()
                 if c.count(s['id']) > c.count(s['id'], 'e.staged_object IS NOT NULL')]
        # A set whose binders are staged over a shared target that is no longer in the
        # scene is ALSO left behind: the .pse holds only the binders (#545 review).
        by_id = {s['id']: s['name'] for s in c.sets()}
        for set_id, record in c.shared_targets().items():
            if record.get('entries') and not _exists(record.get('object'), _self=_self) \
                    and by_id.get(set_id) and by_id[set_id] not in names:
                names.append(by_id[set_id])
    except Exception:
        return False
    if not names:
        return False
    colorprinting.warning(
        ' sets: a .pse cannot hold sets; %s left out. Use `save name.raymol` to keep'
        ' the whole session in one file.' % ', '.join(names))
    return True


def session_restore(session, _self=cmd, **_kwargs):
    """Session-restore task: drop links to staged objects the incoming session does not
    have. Never resets the store -- `set_session` also restores in-memory snapshots
    (the theme preview) and partial loads merge, so the reset for a bare `load x.pse`
    lives in `importing.load_pse`, which knows it is one."""
    try:
        reconcile(_self=_self)
    except Exception as exc:
        colorprinting.warning(' sets: could not reconcile staged objects: %s' % exc)
    return 1


def _app_version(_self=cmd):
    try:
        return str(_self.get_version()[0])
    except Exception:
        return ''


def _pse_bytes(_self=cmd):
    global _SAVING_RAYMOL
    _SAVING_RAYMOL = True
    try:
        session = _self.get_session('', 0, 1)      # session_save strips the peek

        return pickle.dumps(session, 1)
    finally:
        _SAVING_RAYMOL = False


def save_raymol(filename, quiet=1, _self=cmd):
    """`save x.raymol`. If the open container is already this file, write the session
    blob; otherwise copy the container there and continue on the copy.

    Ordered so that no failure loses data: the copy is made to a temporary beside the
    target, the target and any stale `-wal`/`-shm` of a crashed session are removed
    only when the copy exists, the previous file is deleted only after the new one is
    open and holds the session, and on any failure the previous container is reopened
    and reinstalled.
    """
    filename = os.path.abspath(_self.exp_path(filename))
    c = container()
    same = os.path.exists(filename) and os.path.samefile(filename, c.path)
    if not same and store.writers(filename):
        # The document a batch outlived its session in (#448): it is still writing
        # there, so saving over it would replace the campaign with this session.
        raise SetInputError(
            '%s is where %s is still writing its results (it was the document when the'
            ' session was replaced); save this session somewhere else, or load that file'
            ' to go back to it' % (filename, ', '.join(store.writers(filename))))
    if not same:
        old_path = c.path
        tmp = filename + '.saving'
        store.remove_db_files(tmp)
        try:
            moved = c.save_into(tmp)          # closes c
            moved.close()
            store.remove_db_files(filename)   # the target AND a stale WAL beside it
            os.replace(tmp, filename)
            c = store.replace(store.Container(filename))
        except Exception:
            store.remove_db_files(tmp)
            try:
                store.replace(store.Container(old_path))
            except Exception:
                pass
            raise
    try:
        c.write_session(_pse_bytes(_self=_self),
                        pse_version=_self.get_setting_float('pse_export_version'),
                        app_version=_app_version(_self=_self))
    except Exception as exc:
        raise SetInputError('could not write the session into %s: %s' % (filename, exc))
    if not same and (os.path.abspath(old_path) == os.path.abspath(store.working_path())
                     or store.is_preserved(old_path)):
        # force: the ONE place a non-empty working file may still be deleted (#447).
        # Everything in it was just copied into the document the user named, so
        # preserving it would offer them, on the next launch, a recovery of work they
        # explicitly saved -- and a second copy of every structure blob on disk.
        #
        # A PRESERVED container counts as a working file here (#447 review): Save As
        # from a recovered session is exactly the "now put it somewhere I chose" the
        # alert sends the user to, and leaving the recovered_ copy behind would offer
        # it back on the next launch, duplicate every structure blob, and make the
        # docs' "the next Save moves it where you want it" a lie.
        store.retire_working_file(old_path, force=True)
    _self.set('session_file', filename.replace('\\', '/'), quiet=1)
    if not int(quiet):
        colorprinting.parrot(' Save: wrote session and %d set(s) to %s'
                             % (len(c.sets()), filename))
    return _self.DEFAULT_SUCCESS


def checkpoint_session(_self=cmd):
    """Write the current session into the working container, so that what survives a
    quit carries the SCENE as well as the sets (#447, spec §2.1: "the working file for
    an untitled session IS the autosave").

    Called by the app on the way out, not on a timer: it pickles the whole session,
    which is the expensive half of a Save, and the cheap half (the entries) is already
    on disk the moment each result lands. A crash therefore still recovers the sets and
    loses the camera, which is the trade #415 already made everywhere else.

    A no-op unless there is something to protect: no container open (a session that
    never touched a set writes nothing anywhere), a real document open (⌘S is that
    session's answer, and writing behind the user's back is not), or a working file
    with no entries (it is deleted at exit, so a session blob in it is pure cost).
    Returns True when a blob was written.
    """
    if not store.is_open():
        return False
    c = store.active()
    if os.path.abspath(c.path) != os.path.abspath(store.working_path()):
        return False
    # A running batch keeps the file even before its first entry (#448), so it keeps
    # the scene too -- else reopening it says "Scene not recovered" and the target the
    # batch was designing against is gone (#448 review).
    if not c.holds_entries() and not store.writers(c.path):
        return False
    try:
        c.write_session(_pse_bytes(_self=_self),
                        pse_version=_self.get_setting_float('pse_export_version'),
                        app_version=_app_version(_self=_self))
    except Exception as exc:
        colorprinting.warning(' sets: could not checkpoint the session: %s' % exc)
        return False
    return True


def checkpoint_before_replace(_self=cmd):
    """`checkpoint_session` for the moment just BEFORE the scene is replaced (`load`,
    `reinitialize`), and never raising: an untitled session whose working file is about
    to be kept for recovery keeps its scene with it (#448), so reopening the recovered
    file brings back the staged designs and not only the table. Returns True when a
    blob was written."""
    try:
        return checkpoint_session(_self=_self)
    except Exception:
        return False


def _names(running, limit=3):
    names = list(dict.fromkeys(str(n) for n in running or ()))
    if len(names) > limit:
        return '%s and %d more' % (', '.join(names[:limit]), len(names) - limit)
    return ', '.join(names)


def _report_release(event, path=None, running=None, **_):
    """The one console line #448 asks for, whichever path replaced the session: what
    was kept, how many entries, where -- and which batch is still writing there."""
    if event == 'kept':
        sets = [(name, n) for name, n in store.describe_container(path) if n]
        total = sum(n for _, n in sets)
        what = ('%d entr%s in %s' % (total, 'y' if total == 1 else 'ies',
                                      _names([name for name, _ in sets]))
                if total else 'no entries yet')
        line = (' sets: the untitled session\'s sets were never saved, so they were'
                ' kept: %s, at %s. "load" that file to go back to them; it is also'
                ' offered at the next launch.' % (what, path))
        if running:
            line += (' Still running: %s -- its remaining results are written there'
                     ' too.' % _names(running))
        colorprinting.warning(line)
    elif event == 'left' and running:
        total = sum(n for _, n in store.describe_container(path))
        colorprinting.warning(
            ' sets: %s is still running; its remaining results are written to %s'
            ' (%d entr%s there now, no longer open), not to the session that replaced'
            ' it.' % (_names(running), path, total, 'y' if total == 1 else 'ies'))
    return None


store.observe(_report_release)


def _read_session_readonly(path):
    """The session blob of `path` read through a READ-ONLY connection, or None when
    there is none or the file cannot be read that way (the container's own open then
    says why)."""
    import sqlite3
    from urllib.request import pathname2url
    try:
        conn = sqlite3.connect('file:%s?mode=ro' % pathname2url(path), uri=True)
    except Exception:
        return None
    try:
        row = conn.execute('SELECT pse FROM session WHERE id = 1').fetchone()
        return bytes(row[0]) if row and row[0] is not None else None
    except Exception:
        return None
    finally:
        conn.close()


def load_raymol(filename, partial=0, quiet=1, *, _self=cmd):
    """`load x.raymol`. Opens the container IN PLACE, then restores the session blob it
    carries. Later results write straight into the document.

    Validates everything it can before it changes anything: the file opens as ours and
    its session blob unpickles first, then the scene is cleared or replaced, and only
    then is the document installed and the previous working file removed. A partial
    load is refused: it would merge the scene but there is no meaning to merging two
    documents' sets.
    """
    if int(partial):
        raise SetInputError('a .raymol cannot be loaded partially; export the session'
                            ' as .pse and load that partially instead')
    filename = os.path.abspath(_self.exp_path(filename))
    if not os.path.isfile(filename):
        raise SetInputError('no such file: %s' % filename)
    # The session blob is read and unpickled BEFORE the container is opened, because
    # opening migrates an older file in place (#545 review): a file whose session this
    # build cannot read is refused untouched, not refused after it was upgraded.
    store.about_to_open(filename)
    early = _read_session_readonly(filename)
    session = None
    if early is not None:
        try:
            session = pickle.loads(early)
        except Exception as exc:
            raise SetFormatError('%s carries a session this build cannot read: %s'
                                 % (filename, exc))
    new = store.Container(filename)          # SetFormatError if it is not ours
    if early is None:
        # The read-only look found no session (or could not look): ask the container,
        # which is the authority. Unpickled ONCE either way (#545 review round 2).
        try:
            blob = new.read_session()
            session = pickle.loads(blob) if blob else None
        except Exception as exc:
            new.close()
            raise SetFormatError('%s carries a session this build cannot read: %s'
                                 % (filename, exc))
    old = container()
    old_path = old.path
    if session is not None:
        # The scene goes with the working file if that file is about to be kept for
        # recovery (#448): `set_session` below replaces it, and a recovered container
        # without its scene opens as "Scene not recovered". A no-op for a document or
        # a working file with nothing in it. (With no session, `reinitialize` below
        # does this itself.)
        checkpoint_before_replace(_self=_self)
    if session is None:
        # A container written by the store alone (a batch that never saw Save, an
        # exported set) carries no session. Clear the scene FIRST: `reinitialize`
        # resets the store, which would close the document if it were installed.
        _self.reinitialize()
    store.replace(new)
    # A restage notice is about the run that just ended in THAT session; days later,
    # in another, it would describe nothing on screen (#546 review). A recovery notice
    # is the one kind that is about opening the file, and has its own rules (#547).
    for s in new.sets():
        if (new.notice(s['id']) or {}).get('kind') == 'restage':
            new.set_notice(s['id'], None)
    if session is not None:
        r = _self.set_session(session, quiet=quiet, partial=0, steal=1)
    else:
        r = _self.DEFAULT_SUCCESS
    reconcile(_self=_self)
    if os.path.abspath(old_path) == os.path.abspath(store.working_path()) \
            and os.path.abspath(old_path) != os.path.abspath(filename):
        # Not force: opening another document is not permission to discard what the
        # previous, untitled one holds. A batch that landed entries into the working
        # file keeps them, under a recovered_ name, and is offered back on the next
        # launch (#447); a batch still RUNNING keeps it even before its first result,
        # and its later results follow it there (#448). The console line is
        # `_report_release`'s, so this path and `reset()`'s say the same thing.
        store.release_working_file(old_path)
    _self.set('session_file', filename.replace('\\', '/'), quiet=1)
    if session is None and store.is_preserved(filename):
        try:
            after_recovery(_self=_self)
        except Exception as exc:
            colorprinting.warning(' sets: recovered, but could not point you at a set'
                                  ' (%s)' % exc)
    return r


#: `meta` key set when the user DISMISSES a recovered container's "Scene not
#: recovered" notice (#547, `set_notice <set>, 1`). Not written when the notice is
#: shown, nor when a staging action clears it: staging and then crashing again before
#: a save is the same dead end, and the next Open must say so again (review round 1).
#: The trigger itself already requires a session-less open.
RECOVERY_NOTICE_KEY = 'recovery_notice'

#: `meta` key naming the set the drawer was last opened on -- "the most recently
#: active set" a recovery points at. Written by `appkit_sets.open_set`.
LAST_ACTIVE_KEY = 'last_active_set'

RECOVERY_TEXT = 'Scene not recovered.'


def most_recently_active_set(c):
    """The set the user was last working in: the one the drawer was last opened on,
    else the one that received the newest entry, else the newest set. None when the
    file has no sets."""
    sets = c.sets()
    if not sets:
        return None
    by_id = {s['id']: s for s in sets}
    last = c.meta_get(LAST_ACTIVE_KEY, '') or ''
    if last in by_id:
        return by_id[last]
    newest = None
    for s in sets:
        rows = c.entries(s['id'], order_by='e.created DESC', limit=1)
        stamp = rows[0]['created'] if rows else s.get('created') or 0
        if newest is None or stamp > newest[0]:
            newest = (stamp, s)
    return newest[1]


def after_recovery(_self=cmd):
    """A recovered container was opened and the scene did not come back with it
    (#547): the sets, stars and views are there, and nothing is staged. Put a notice
    on the most recently active set -- the drawer draws it as `Scene not recovered.
    [Stage N starred] [Apply <view>] [Dismiss]` -- open the drawer on that set, and
    say the same on the console, with the command, for an agent or a user without
    the drawer. Not after an explicit Dismiss (`RECOVERY_NOTICE_KEY`). Returns the set's name, or '' when there was nothing to point at."""
    c = container()
    if c.meta_get(RECOVERY_NOTICE_KEY):
        return ''
    row = most_recently_active_set(c)
    if row is None:
        return ''
    c.set_notice(row['id'], {'kind': 'recovered', 'text': RECOVERY_TEXT})
    try:
        from pymol import appkit_sets
        appkit_sets.open_set(row['name'], _self=_self)
    except Exception:
        pass
    # The same entries the drawer's "Stage N starred" counts, and the same cut to the
    # budget its "Stage top K starred" makes.
    starred = stageable_starred(c, row)
    views = c.views(row['id'])
    hints = []
    if starred:
        chosen, label = pick_to_fit(c, row, starred, _self=_self)
        if len(chosen) == len(starred):
            hints.append('"set_stage %s, starred" puts its %d starred entr%s back'
                         % (row['name'], len(starred), 'y' if len(starred) == 1 else 'ies'))
        elif chosen:
            hints.append('"set_stage %s, %s" stages the top %d of its %d starred entries'
                         ' (%s; the budget is %d)'
                         % (row['name'], '+'.join(e['name'] for e in chosen), len(chosen),
                            len(starred), 'by %s' % label if label else 'in delivery order',
                            budget(row)))
        else:
            hints.append('its %d starred entries do not fit the stage budget (%d);'
                         ' unstage some or raise it with set_budget'
                         % (len(starred), budget(row)))
    if views:
        # What the drawer's "Apply <view>" does: the view's filter and sort become the
        # set's. Not `set_stage ..., view:`, which would usually be over budget.
        view = views[-1]
        steps = ['"set_filter %s, %s"' % (row['name'], view['filter'])
                 if view.get('filter') else '"set_filter %s"' % row['name']]
        if view.get('sort_key'):
            steps.append('"set_sort %s, %s, %d"' % (row['name'], view['sort_key'],
                                                     int(view.get('sort_desc', 1))))
        hints.append('its view %s applies with %s' % (view['name'], ' and '.join(steps)))
    colorprinting.parrot(' sets: %s -- the sets came back, the scene did not.%s'
                         % (row['name'], (' ' + '; '.join(hints) + '.') if hints else ''))
    return row['name']
